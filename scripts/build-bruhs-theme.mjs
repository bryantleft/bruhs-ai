// Regenerate the vendored stylesheet without adding Node to the Trunk build.
// Usage: node scripts/build-bruhs-theme.mjs /absolute/path/to/package /absolute/path/to/tools
// package: npm pack @bruhs/theme@0.3.0, extracted; tools: npm install --prefix ... purgecss@7.0.2
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { resolve, dirname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { createHash } from 'node:crypto';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const [packageDir, toolsDir] = process.argv.slice(2);
if (!packageDir || !toolsDir) throw new Error('Provide the extracted theme package and build-tools directory.');
const require = createRequire(resolve(toolsDir, 'package.json'));
const { PurgeCSS } = require('purgecss');
const postcss = require('postcss');
const manifest = JSON.parse(readFileSync(resolve(packageDir, 'package.json'), 'utf8'));
if (manifest.name !== '@bruhs/theme' || manifest.version !== '0.3.0') throw new Error('Expected @bruhs/theme@0.3.0');
const source = readFileSync(resolve(packageDir, 'dist/bruhs.css'), 'utf8');
const [result] = await new PurgeCSS().purge({
  content: [resolve(root, 'bruhs-web/index.html'), resolve(root, 'bruhs-web/src/**/*.rs'), resolve(root, 'bruhs-models/src/**/*.rs')],
  css: [{ raw: source }],
  defaultExtractor: content => content.match(/[A-Za-z0-9_!:@/.[\]%-]+/g) || [],
  // Preserve tokens, font faces, and animations; only unused selector rules are removed.
  variables: false, fontFace: false, keyframes: false,
});
const parsed = postcss.parse(result.css);
parsed.walkAtRules('font-face', rule => {
  rule.walkDecls('src', declaration => {
    const font = declaration.value.match(/Monaspace[A-Za-z]+Variable\.woff2/);
    if (!font) throw new Error(`Unrecognized font: ${declaration.value}`);
    const name = basename(font[0]);
    if (!existsSync(resolve(root, 'bruhs-web/fonts', name))) throw new Error(`Missing local font ${name}`);
    declaration.value = `url("/fonts/${name}") format("woff2")`;
  });
});
const outputDir = resolve(root, 'bruhs-web/vendor');
mkdirSync(outputDir, { recursive: true });
writeFileSync(resolve(outputDir, 'bruhs.css'), parsed.toString());
writeFileSync(resolve(outputDir, 'BRUHS-LICENSE'), readFileSync(resolve(packageDir, 'LICENSE')));
writeFileSync(resolve(outputDir, 'bruhs-source.json'), JSON.stringify({
  package: '@bruhs/theme', version: manifest.version, buildTool: 'purgecss@7.0.2',
  sourceSha256: createHash('sha256').update(source).digest('hex'),
  sourceBytes: Buffer.byteLength(source), outputBytes: Buffer.byteLength(parsed.toString()),
  note: 'Generated by scripts/build-bruhs-theme.mjs; original tokens preserved; font URLs use bundled local WOFF2 assets.',
}, null, 2) + '\n');
console.log(`Bruhs CSS: ${Buffer.byteLength(source)} -> ${Buffer.byteLength(parsed.toString())} bytes`);
