//! Clean the forge’s own proposed message before freezing a reviewed merge command.
use super::*;
use serde_json::Value;

fn known_agent(line: &str) -> bool {
    let lower = line.trim().to_ascii_lowercase();
    let text = lower
        .strip_prefix("- ")
        .or_else(|| lower.strip_prefix("* "))
        .unwrap_or(&lower)
        .trim();
    if let Some(author) = text.strip_prefix("co-authored-by:") {
        let Some((name, email)) = author
            .trim()
            .strip_suffix('>')
            .and_then(|s| s.rsplit_once('<'))
        else {
            return false;
        };
        return match email {
            "noreply@github.com" => matches!(name.trim(), "copilot" | "github copilot"),
            "noreply@anthropic.com"
            | "claude@anthropic.com"
            | "noreply@openai.com"
            | "codex@openai.com"
            | "cursoragent@cursor.com"
            | "copilot@github.com" => true,
            _ => false,
        };
    }
    let text = text.trim_start_matches('🤖').trim_start();
    let Some(agent) = text
        .strip_prefix("generated with ")
        .or_else(|| text.strip_prefix("generated by "))
    else {
        return false;
    };
    let agent = agent.trim_end_matches(['.', '!']);
    let agent = if let Some((name, url)) = agent
        .strip_prefix('[')
        .and_then(|s| s.strip_suffix(')'))
        .and_then(|s| s.split_once("]("))
    {
        let Ok(url) = reqwest::Url::parse(url) else {
            return false;
        };
        if url.scheme() != "https"
            || !url.username().is_empty()
            || url.password().is_some()
            || !matches!(
                url.host_str(),
                Some(
                    "claude.ai"
                        | "claude.com"
                        | "www.anthropic.com"
                        | "chatgpt.com"
                        | "openai.com"
                        | "cursor.com"
                        | "github.com"
                        | "opencode.ai"
                        | "x.ai"
                        | "antigravity.google"
                )
            )
        {
            return false;
        }
        name
    } else {
        agent
    };
    matches!(
        agent,
        "claude"
            | "claude code"
            | "codex"
            | "cursor"
            | "github copilot"
            | "copilot"
            | "opencode"
            | "grok"
            | "antigravity"
    )
}
fn cleaned(message: &str) -> Option<String> {
    let mut fence = None;
    let mut result = String::new();
    let mut removed = false;
    for original in message.split_inclusive('\n') {
        let line = original.trim_end_matches(['\r', '\n']);
        let content = line.trim_start_matches(' ');
        let marker = content.bytes().next().filter(|c| matches!(c, b'`' | b'~'));
        let width = marker.map_or(0, |c| content.bytes().take_while(|p| *p == c).count());
        let indented = line.starts_with("    ") || line.starts_with('\t');
        if !indented && width >= 3 {
            let suffix = &content[width..];
            match fence {
                None if marker == Some(b'~') || !suffix.contains('`') => {
                    fence = Some((marker, width))
                }
                Some((open, len)) if open == marker && width >= len && suffix.trim().is_empty() => {
                    fence = None
                }
                _ => {}
            }
        } else if !indented && fence.is_none() && known_agent(line) {
            removed = true;
            continue;
        }
        result.push_str(original);
    }
    if !removed {
        return None;
    }
    while let Some((before, tail)) = result.rsplit_once('\n') {
        if !tail.trim().is_empty() {
            break;
        }
        result.truncate(before.strip_suffix('\r').unwrap_or(before).len());
    }
    Some(result)
}
const GITHUB:&str="query($owner:String!,$name:String!,$number:Int!,$method:PullRequestMergeMethod!){repository(owner:$owner,name:$name){pullRequest(number:$number){headRefOid isMergeQueueEnabled viewerMergeBodyText(mergeType:$method)}}}";
const GITLAB:&str="query($project:ID!,$iid:String!){project(fullPath:$project){mergeRequest(iid:$iid){diffHeadSha title squashOnMerge defaultMergeCommitMessage defaultSquashCommitMessage}}}";
impl DeliveryService {
    pub(super) async fn clean_merge_message(
        &self,
        path: &Path,
        repo: &ForgeRepository,
        number: u64,
        head: &str,
        method: MergeMethod,
        command: &mut Command,
    ) -> DeliveryResult<()> {
        let invalid = || {
            DeliveryError::Invalid(
                "The forge did not return a merge message for the reviewed pull request.".into(),
            )
        };
        let github = repo.forge == Forge::GitHub;
        let mut args = vec![
            "api".to_owned(),
            "graphql".into(),
            "--hostname".into(),
            repo.host.clone(),
        ];
        if github {
            let (owner, name) = repo.project.split_once('/').ok_or_else(invalid)?;
            let method = if method == MergeMethod::Squash {
                "SQUASH"
            } else {
                "MERGE"
            };
            args.extend([
                "-f".into(),
                format!("query={GITHUB}"),
                "-f".into(),
                format!("owner={owner}"),
                "-f".into(),
                format!("name={name}"),
                "-F".into(),
                format!("number={number}"),
                "-f".into(),
                format!("method={method}"),
            ]);
        } else {
            args.extend([
                "-f".into(),
                format!("query={GITLAB}"),
                "-f".into(),
                format!("project={}", repo.project),
                "-f".into(),
                format!("iid={number}"),
            ]);
        }
        let args: Vec<_> = args.iter().map(String::as_str).collect();
        let output = self
            .read_scoped(path, if github { "gh" } else { "glab" }, &args, Some(repo))
            .await?;
        let json: Value = serde_json::from_str(&output).map_err(|_| invalid())?;
        if json.get("errors").is_some() {
            return Err(invalid());
        }
        if github {
            let pr = &json["data"]["repository"]["pullRequest"];
            if pr["isMergeQueueEnabled"].as_bool().ok_or_else(invalid)? {
                return Ok(());
            }
            if pr["headRefOid"].as_str() != Some(head) {
                return Err(DeliveryError::Conflict(
                    "The pull request head changed. Refresh before preparing the merge.".into(),
                ));
            }
            if let Some(body) = cleaned(pr["viewerMergeBodyText"].as_str().ok_or_else(invalid)?) {
                command.args.extend(["--body-file".into(), "-".into()]);
                command.stdin = Some(body);
            }
        } else {
            let mr = &json["data"]["project"]["mergeRequest"];
            if mr["diffHeadSha"].as_str() != Some(head) {
                return Err(DeliveryError::Conflict(
                    "The merge request head changed. Refresh before preparing the merge.".into(),
                ));
            }
            let mut payload: Value =
                serde_json::from_str(command.stdin.as_deref().ok_or_else(invalid)?)
                    .map_err(|_| invalid())?;
            for (field, target) in [
                ("defaultMergeCommitMessage", "merge_commit_message"),
                ("defaultSquashCommitMessage", "squash_commit_message"),
            ] {
                if target == "squash_commit_message"
                    && !(method == MergeMethod::Squash || mr["squashOnMerge"] == true)
                {
                    continue;
                }
                if let Some(clean) = mr[field].as_str().and_then(cleaned) {
                    payload[target] = if clean.is_empty() {
                        mr["title"].as_str().ok_or_else(invalid)?.into()
                    } else {
                        clean.into()
                    };
                    if target == "squash_commit_message" {
                        payload["squash"] = true.into();
                    }
                }
            }
            command.stdin = Some(payload.to_string());
        }
        Ok(())
    }
}
#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn strips_recognized_credits_preserving_humans_code_and_line_endings() {
        let input="Keep this\r\nCo-authored-by: Human <noreply@github.com>\r\n~~~text\r\nGenerated with Codex\r\n~~~\r\n    Generated by Cursor\r\nCo-authored-by: Claude <noreply@anthropic.com>\r\n🤖 Generated with [Claude Code](https://claude.ai/code)\r\n";
        assert_eq!(cleaned(input).as_deref(),Some("Keep this\r\nCo-authored-by: Human <noreply@github.com>\r\n~~~text\r\nGenerated with Codex\r\n~~~\r\n    Generated by Cursor"));
        assert_eq!(
            cleaned("Generated by [Cursor](https://unrelated.example)"),
            None
        );
        assert_eq!(cleaned("Generated by Codex."), Some(String::new()));
    }
}

#[cfg(all(test, unix))]
#[tokio::test]
async fn forge_messages_are_cleaned_only_for_the_reviewed_head_and_frozen_in_the_plan() {
    use std::os::unix::fs::PermissionsExt;
    let dir = tempfile::tempdir().unwrap();
    let repo = crate::delivery::tests::repository();
    let path = repo.path().canonicalize().unwrap();
    let storage = dir.path().join("delivery");
    let mut service = DeliveryService::open(storage).await.unwrap();
    let cli = dir.path().join("forge");
    std::fs::write(
        &cli,
        "#!/bin/sh\nif [ \"$2\" = graphql ]; then exec /bin/cat \"$0.json\"; fi\nexit 1\n",
    )
    .unwrap();
    std::fs::set_permissions(&cli, std::fs::Permissions::from_mode(0o700)).unwrap();
    service.gh = Arc::new(cli.clone());
    service.glab = Arc::new(cli.clone());
    let head = "a".repeat(40);
    let make = || PrepareRequest {
        path: path.display().to_string(),
        forge: Forge::Auto,
        timeout_seconds: 5,
        action: DeliveryAction::Merge {
            number: 42,
            head_oid: head.clone(),
            method: MergeMethod::Squash,
            auto: true,
        },
    };
    let body = "Release notes\n\nCo-authored-by: Human <dev@example.org>\nGenerated with Codex";
    let expected = "Release notes\n\nCo-authored-by: Human <dev@example.org>";
    assert!(service.prepare(make()).await.unwrap().commands[0]
        .stdin
        .is_none());
    service
        .set_preference(
            None,
            DeliveryPreferenceChange::RemoveAgentCredits(Some(true)),
        )
        .await
        .unwrap();
    let mut response = serde_json::json!({"data":{"repository":{"pullRequest":{"isMergeQueueEnabled":false,"headRefOid":head,"viewerMergeBodyText":body}}}});
    let response_file = cli.with_extension("json");
    std::fs::write(&response_file, response.to_string()).unwrap();
    let plan = service.prepare(make()).await.unwrap();
    assert_eq!(plan.commands[0].stdin.as_deref(), Some(expected));
    assert!(plan.commands[0].args.contains(&"--auto".into()));
    assert!(plan.commands[0]
        .args
        .ends_with(&["--body-file".into(), "-".into()]));
    response["data"]["repository"]["pullRequest"]["isMergeQueueEnabled"] = true.into();
    std::fs::write(&response_file, response.to_string()).unwrap();
    assert!(service.prepare(make()).await.unwrap().commands[0]
        .stdin
        .is_none());
    response["data"]["repository"]["pullRequest"]["isMergeQueueEnabled"] = false.into();
    response["data"]["repository"]["pullRequest"]["headRefOid"] = "b".repeat(40).into();
    std::fs::write(&response_file, response.to_string()).unwrap();
    assert!(matches!(
        service.prepare(make()).await,
        Err(DeliveryError::Conflict(_))
    ));
    service
        .set_preference(
            Some(&path),
            DeliveryPreferenceChange::RemoveAgentCredits(Some(false)),
        )
        .await
        .unwrap();
    assert!(service.prepare(make()).await.unwrap().commands[0]
        .stdin
        .is_none());
    service
        .set_preference(
            Some(&path),
            DeliveryPreferenceChange::RemoveAgentCredits(None),
        )
        .await
        .unwrap();
    assert!(std::process::Command::new("git")
        .current_dir(&path)
        .args([
            "remote",
            "set-url",
            "origin",
            "https://gitlab.com/fixture/repo.git"
        ])
        .status()
        .unwrap()
        .success());
    std::fs::write(&response_file,serde_json::json!({"data":{"project":{"mergeRequest":{"title":"Title","diffHeadSha":head,"squashOnMerge":true,"defaultMergeCommitMessage":body,"defaultSquashCommitMessage":"Generated by Codex"}}}}).to_string()).unwrap();
    let plan = service.prepare(make()).await.unwrap();
    let payload: Value = serde_json::from_str(plan.commands[0].stdin.as_ref().unwrap()).unwrap();
    assert_eq!(payload["merge_commit_message"], expected);
    assert_eq!(payload["squash_commit_message"], "Title");
    assert_eq!(payload["auto_merge"], true);
    assert_eq!(payload["sha"], head);
}
