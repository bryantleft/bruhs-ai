//! Preserve unchanged prose nodes between streaming updates. Parsing and URL
//! policy stay in the complete-document Markdown renderer, so later reference
//! definitions and incomplete constructs can still change earlier output.

use leptos::tachys::html::element::InnerHtmlValue;
use web_sys::Element;

#[cfg(target_arch = "wasm32")]
#[wasm_bindgen::prelude::wasm_bindgen(module = "/src/markdown/dom.js")]
extern "C" {
    #[wasm_bindgen::prelude::wasm_bindgen(js_name = patchSanitizedMarkdown)]
    fn patch_sanitized_markdown(element: &Element, html: &str);
}

/// Only the sanitizer can construct this value; DOM reconciliation never
/// receives raw model output. The retained state has the same ownership as
/// Tachys's ordinary String inner_html value and dies with the prose element.
#[derive(Clone)]
pub(crate) struct ProseHtml(String);

pub(crate) fn render(markdown: &str) -> ProseHtml {
    ProseHtml(super::render_untrusted(markdown))
}

/// Slots are generated by the rich Markdown parser, never model HTML. Keep
/// table/list containers in the sanitizer while mounting typed media inside.
pub(crate) fn render_slots(markdown: &str, slots: &[(&str, &str)]) -> ProseHtml {
    if slots.is_empty() {
        return render(markdown);
    }
    let mut html = super::render_untrusted(markdown);
    for (marker, id) in slots {
        let id = id
            .replace('&', "&amp;")
            .replace('"', "&quot;")
            .replace('<', "&lt;");
        html = html.replace(
            marker,
            &format!("<span data-rich-media-slot=\"{id}\" data-bruhs-managed=\"{id}\"></span>"),
        );
    }
    ProseHtml(html)
}

impl InnerHtmlValue for ProseHtml {
    type AsyncOutput = Self;
    type State = (Element, String);
    type Cloneable = Self;
    type CloneableOwned = Self;

    fn html_len(&self) -> usize {
        self.0.len()
    }

    fn to_html(self, buf: &mut String) {
        buf.push_str(&self.0);
    }

    fn to_template(_buf: &mut String) {}

    fn hydrate<const FROM_SERVER: bool>(self, element: &Element) -> Self::State {
        self.0.hydrate::<FROM_SERVER>(element)
    }

    fn build(self, element: &Element) -> Self::State {
        self.0.build(element)
    }

    fn rebuild(self, state: &mut Self::State) {
        if self.0 == state.1 {
            return;
        }
        #[cfg(target_arch = "wasm32")]
        patch_sanitized_markdown(&state.0, &self.0);
        #[cfg(not(target_arch = "wasm32"))]
        state.0.set_inner_html(&self.0);
        state.1 = self.0;
    }

    fn into_cloneable(self) -> Self::Cloneable {
        self
    }

    fn into_cloneable_owned(self) -> Self::CloneableOwned {
        self
    }

    fn dry_resolve(&mut self) {}

    async fn resolve(self) -> Self::AsyncOutput {
        self
    }
}
