//! Lucide-style inline SVG icons.
//!
//! Icons mirror the set used by the TS bruhs app (lucide-react) and Zed/GPUI's
//! built-in set, kept inline so there's no HTTP round-trip and so
//! `currentColor` fills inherit from text utility classes. All paths come from
//! Lucide (MIT License, https://lucide.dev).
//!
//! Usage:
//! ```
//! <Icon name="folder" class="text-rambutan-500" />
//! <Icon name="send" size=18 />
//! ```
//!
//! Size defaults to 14 (pairs with `text-label-sm`). Stroke width is 2 to
//! match Lucide's standard look.

use leptos::prelude::*;
use leptos::svg::Svg;

#[component]
pub fn Icon(
    /// Icon name — see the match in this file for the full list.
    #[prop(into)]
    name: String,
    /// Pixel size (square). Default 14.
    #[prop(optional)]
    size: Option<u32>,
    /// Extra Tailwind classes (color, margin, etc.). `currentColor` is used
    /// for strokes so `text-*` utilities work directly.
    #[prop(optional, into)]
    class: String,
) -> impl IntoView {
    let size = size.unwrap_or(14);
    let node_ref = NodeRef::<Svg>::new();

    // All icons share the same outer attributes — only the inner paths differ.
    // `inner_html` only ever receives these compiled-in SVG strings.
    let inner = icon_body(&name);

    view! {
        <svg
            node_ref=node_ref
            xmlns="http://www.w3.org/2000/svg"
            width=size
            height=size
            viewBox="0 0 24 24"
            fill="none"
            stroke="currentColor"
            stroke-width="2"
            stroke-linecap="round"
            stroke-linejoin="round"
            class=format!("inline-block shrink-0 {class}")
            inner_html=inner
        />
    }
}

